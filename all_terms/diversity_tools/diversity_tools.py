# ===============================
# MIN SCORE GLOBAL
# ===============================

MIN_SCORE = min(score for row in BLOSUM62.values() for score in row.values())


# ===============================
# DISTANCIA BLOSUM62
# ===============================

def blosum62_distance(seq1: str, seq2: str) -> float:

    if len(seq1) != len(seq2):
        return np.nan

    total_dist = 0.0
    max_dist = 0.0

    for aa1, aa2 in zip(seq1, seq2):

        if aa1 not in BLOSUM62 or aa2 not in BLOSUM62[aa1]:
            score = MIN_SCORE
        else:
            score = BLOSUM62[aa1][aa2]

        max_score = BLOSUM62.get(aa1, {}).get(aa1, 0)

        total_dist += (max_score - score)
        max_dist += (max_score - MIN_SCORE)

    if max_dist == 0:
        return 0.0

    return total_dist / max_dist


# ===============================
# DIVERSIDAD POBLACIONAL
# ===============================

def population_diversity_blosum62(sequences: list) -> float:
    """
    Calcula la diversidad promedio de una población de secuencias.
    Es el promedio de distancias BLOSUM62 entre todos los pares.
    """

    n = len(sequences)

    if n < 2:
        return 0.0

    distances = []

    for i in range(n):
        for j in range(i + 1, n):

            d = blosum62_distance(sequences[i], sequences[j])

            if not np.isnan(d):
                distances.append(d)

    if len(distances) == 0:
        return 0.0

    return float(np.mean(distances))